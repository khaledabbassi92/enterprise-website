// DELETE RAW MEDIA FILE (PROTECTED) - CASCADES & SCRUBS ALL REFERENCES
router.delete(
  "/:id",
  requireAdminAuth,
  (req, res) => {
    try {
      const filename =
        path.basename(req.params.id);

      const filePath =
        path.join(
          projectsDirectory,
          filename
        );

      // 1. Delete file from disk
      if (fs.existsSync(filePath)) {
        fs.unlinkSync(filePath);
      }

      // 2. Cascade cleanup in media.json
      const config = readMediaConfig();

      let modified = false;

      if (config.homepage) {
        for (const slot of HOMEPAGE_SLOTS) {
          if (
            config.homepage[slot] &&
            config.homepage[slot].file ===
              filename
          ) {
            config.homepage[slot] = null;
            modified = true;
          }
        }

        if (
          Array.isArray(
            config.homepage.gallery?.facades
          )
        ) {
          config.homepage.gallery.facades =
            config.homepage.gallery.facades.map(
              (f) => {
                let updated = { ...f };

                if (
                  updated.file === filename
                ) {
                  updated.file = null;
                  modified = true;
                }

                if (
                  Array.isArray(
                    updated.subimages
                  ) &&
                  updated.subimages.includes(
                    filename
                  )
                ) {
                  updated.subimages =
                    updated.subimages.filter(
                      (sub) =>
                        sub !== filename
                    );

                  modified = true;
                }

                return updated;
              }
            );
        }
      }

      if (modified) {
        writeMediaConfig(config);
      }

      return res.json({
        success: true,
        message:
          "Média supprimé et références nettoyées.",
      });
    } catch (err) {
      console.error(
        "❌ DELETE media error:",
        err
      );

      return res.status(500).json({
        success: false,
        message:
          "Erreur suppression média.",
      });
    }
  }
);

