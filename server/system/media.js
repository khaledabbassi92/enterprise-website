const express = require("express");
const multer = require("multer");
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const { requireAdminAuth } = require("./admin");

const router = express.Router();

const projectsDirectory = path.join(__dirname, "projects");
const mediaConfigPath = path.join(__dirname, "..", "media.json");

if (!fs.existsSync(projectsDirectory)) {
  fs.mkdirSync(projectsDirectory, { recursive: true });
}

const DEFAULT_MEDIA_CONFIG = {
  homepage: {
    banner: null,
    introduction: null,
    finale: null,
    gallery: { facades: [] },
  },
};

const HOMEPAGE_SLOTS = ["banner", "introduction", "finale"];

function createMediaUrl(filename) {
  return `/api/media/file/${encodeURIComponent(filename)}`;
}

function checkFileExists(filename) {
  if (!filename) return false;

  try {
    const cleanName = path.basename(filename);
    const filePath = path.join(projectsDirectory, cleanName);

    return fs.existsSync(filePath);
  } catch {
    return false;
  }
}

function readMediaConfig() {
  try {
    if (!fs.existsSync(mediaConfigPath)) {
      fs.writeFileSync(
        mediaConfigPath,
        JSON.stringify(DEFAULT_MEDIA_CONFIG, null, 2),
        "utf8"
      );

      return DEFAULT_MEDIA_CONFIG;
    }

    const raw = fs.readFileSync(mediaConfigPath, "utf8");

    if (!raw.trim()) {
      return DEFAULT_MEDIA_CONFIG;
    }

    const parsed = JSON.parse(raw);

    const facades =
      parsed.homepage?.gallery?.facades ||
      parsed.homepage?.gallery?.facade ||
      [];

    return {
      homepage: {
        banner: parsed.homepage?.banner ?? null,
        introduction: parsed.homepage?.introduction ?? null,
        finale: parsed.homepage?.finale ?? null,
        gallery: {
          facades: Array.isArray(facades) ? facades : [facades],
        },
      },
    };
  } catch (err) {
    console.error("❌ Erreur lecture media.json:", err.message);

    return DEFAULT_MEDIA_CONFIG;
  }
}

function writeMediaConfig(config) {
  try {
    fs.writeFileSync(
      mediaConfigPath,
      JSON.stringify(config, null, 2),
      "utf8"
    );

    return true;
  } catch (err) {
    console.error("❌ Erreur écriture media.json:", err.message);

    return false;
  }
}

/*
|--------------------------------------------------------------------------
| GET ALL MEDIA (PUBLIC)
|--------------------------------------------------------------------------
|
| IMPORTANT:
| Files uploaded by this server are named:
|
|     Date.now()-randomhex.ext
|
| Therefore the Date.now() prefix is the most reliable upload ordering
| mechanism.
|
| Newest media is ALWAYS returned first.
|
*/
router.get("/", (req, res) => {
  try {
    if (!fs.existsSync(projectsDirectory)) {
      return res.status(200).json({
        success: true,
        media: [],
      });
    }

    const files = fs.readdirSync(projectsDirectory, {
      withFileTypes: true,
    });

    const media = files
      .filter((entry) => entry.isFile())
      .map((entry) => {
        const fullPath = path.join(projectsDirectory, entry.name);

        let timestamp = 0;

        /*
         * PRIMARY ORDERING METHOD
         *
         * Uploaded files generated by multer have:
         *
         *     1756638123456-a8f92c....jpg
         *
         * The first number is Date.now().
         */
        const match = entry.name.match(/^(\d{13})[-_]/);

        if (match) {
          const parsedTimestamp = Number(match[1]);

          if (
            Number.isFinite(parsedTimestamp) &&
            parsedTimestamp > 0
          ) {
            timestamp = parsedTimestamp;
          }
        }

        /*
         * FALLBACK
         *
         * For older files that don't have the Date.now() prefix,
         * use the filesystem timestamps.
         */
        if (timestamp === 0) {
          try {
            const stats = fs.statSync(fullPath);

            timestamp = Math.max(
              Number(stats.birthtimeMs) || 0,
              Number(stats.mtimeMs) || 0,
              Number(stats.ctimeMs) || 0
            );
          } catch {
            timestamp = 0;
          }
        }

        return {
          id: entry.name,
          name: entry.name,
          url: createMediaUrl(entry.name),
          timestamp,
        };
      })
      /*
       * NEWEST FIRST
       *
       * Larger timestamp = newer file.
       */
      .sort((a, b) => {
        if (b.timestamp !== a.timestamp) {
          return b.timestamp - a.timestamp;
        }

        /*
         * Stable fallback if two files somehow have the exact
         * same timestamp.
         */
        return b.name.localeCompare(a.name);
      })
      .map(({ id, name, url }) => ({
        id,
        name,
        url,
      }));

    return res.status(200).json({
      success: true,
      media,
    });
  } catch (err) {
    console.error("❌ GET media error:", err);

    return res.status(500).json({
      success: false,
      message: "Erreur lecture médias.",
    });
  }
});

// GET HOMEPAGE SLOTS (PUBLIC) - AUTO-CLEANS DELETED / MISSING IMAGES FROM JSON
router.get("/homepage-slots", (req, res) => {
  try {
    const config = readMediaConfig();
    const homepageConfig = config.homepage || {};
    const slots = {};
    let modified = false;

    for (const slotName of HOMEPAGE_SLOTS) {
      const slot = homepageConfig[slotName];

      if (slot && slot.file) {
        if (checkFileExists(slot.file)) {
          slots[slotName] = {
            ...slot,
            url: createMediaUrl(slot.file),
          };
        } else {
          homepageConfig[slotName] = null;
          slots[slotName] = null;
          modified = true;
        }
      } else {
        slots[slotName] = null;
      }
    }

    if (modified) {
      config.homepage = homepageConfig;
      writeMediaConfig(config);
    }

    return res.status(200).json({
      success: true,
      slots,
    });
  } catch (err) {
    console.error("❌ GET slots error:", err);

    return res.status(500).json({
      success: false,
      message: "Erreur lecture des images homepage.",
    });
  }
});

// GET FACADE GALLERY (PUBLIC) - AUTO-CLEANS DEAD MAIN & SUBIMAGE URLS FROM JSON
router.get("/gallery/facade", (req, res) => {
  try {
    const config = readMediaConfig();
    const rawFacades =
      config.homepage?.gallery?.facades || [];

    let modified = false;

    const facades = rawFacades.map((f) => {
      let item = { ...f };

      // 1. Verify main image exists on disk
      if (item.file && !checkFileExists(item.file)) {
        item.file = null;
        item.url = null;
        modified = true;
      } else {
        item.url = item.file
          ? createMediaUrl(item.file)
          : null;
      }

      // 2. Verify and filter subimages against actual disk files
      if (Array.isArray(item.subimages)) {
        const validSubimages = item.subimages.filter(
          (subfile) => {
            const exists = checkFileExists(subfile);

            if (!exists) {
              modified = true;
            }

            return exists;
          }
        );

        item.subimages = validSubimages;

        item.subimagesUrls = validSubimages.map(
          (subfile) => createMediaUrl(subfile)
        );
      } else {
        item.subimages = [];
        item.subimagesUrls = [];
      }

      return item;
    });

    if (modified) {
      if (!config.homepage) {
        config.homepage = {};
      }

      if (!config.homepage.gallery) {
        config.homepage.gallery = {};
      }

      config.homepage.gallery.facades = facades.map(
        ({ subimagesUrls, url, ...rest }) => rest
      );

      writeMediaConfig(config);
    }

    return res.status(200).json({
      success: true,
      facades,
      facade: facades[0] || null,
    });
  } catch (err) {
    console.error("❌ GET facade error:", err);

    return res.status(500).json({
      success: false,
      message: "Erreur lecture galerie façade.",
    });
  }
});

// SERVE MEDIA FILE (PUBLIC)
