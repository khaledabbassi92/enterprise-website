// UPDATE FACADE GALLERY (PROTECTED)
router.put(
  "/gallery/facade",
  requireAdminAuth,
  (req, res) => {
    try {
      const {
        file,
        title,
        description,
        index,
        x,
        y,
        width,
        height,
        zoom,
        offsetX,
        offsetY,
      } = req.body || {};

      if (!file) {
        return res.status(400).json({
          success: false,
          message: "Fichier manquant.",
        });
      }

      const cleanFile = path.basename(file);

      if (!checkFileExists(cleanFile)) {
        return res.status(404).json({
          success: false,
          message:
            "Le fichier spécifié n'existe pas sur le serveur.",
        });
      }

      const config = readMediaConfig();

      if (!config.homepage) {
        config.homepage = {
          banner: null,
          introduction: null,
          finale: null,
          gallery: {
            facades: [],
          },
        };
      }

      if (!config.homepage.gallery) {
        config.homepage.gallery = {
          facades: [],
        };
      }

      let facades =
        config.homepage.gallery.facades || [];

      const targetIndex =
        Number(index) || facades.length + 1;

      const existingIdx = facades.findIndex(
        (f) => Number(f.index) === targetIndex
      );

      const existingSubimages =
        (
          existingIdx !== -1 &&
          Array.isArray(facades[existingIdx].subimages)
            ? facades[existingIdx].subimages
            : []
        ).filter((sub) => checkFileExists(sub));

      const item = {
        file: cleanFile,
        title: title || "",
        description: description || "",
        index: targetIndex,
        x: Number(x) || 50,
        y: Number(y) || 50,
        width: Number(width) || 60,
        height: Number(height) || 45,
        zoom: Number(zoom) || 1.6667,
        offsetX: Number(offsetX) || 0,
        offsetY: Number(offsetY) || 0,
        subimages: existingSubimages,
      };

      if (existingIdx !== -1) {
        facades[existingIdx] = item;
      } else {
        facades.push(item);
      }

      config.homepage.gallery.facades = facades;

      if (!writeMediaConfig(config)) {
        return res.status(500).json({
          success: false,
          message:
            "Impossible d'enregistrer la galerie.",
        });
      }

      return res.json({
        success: true,
        facade: item,
      });
    } catch (err) {
      console.error(
        "❌ PUT facade gallery error:",
        err
      );

      return res.status(500).json({
        success: false,
        message:
          "Erreur enregistrement galerie.",
      });
    }
  }
);

// UPDATE SUBIMAGES (PROTECTED) - TOGGLE/MERGE & DISK EXISTENCE CHECK
router.put(
  "/gallery/subimages",
  requireAdminAuth,
  (req, res) => {
    try {
      const { index, filenames } = req.body || {};

      const targetIndex = Number(index);

      if (
        !Number.isInteger(targetIndex) ||
        targetIndex < 1
      ) {
        return res.status(400).json({
          success: false,
          message: "Index invalide.",
        });
      }

      const incomingFiles = (
        Array.isArray(filenames)
          ? filenames
          : [filenames]
      )
        .filter(Boolean)
        .map((f) => path.basename(f));

      if (!incomingFiles.length) {
        return res.status(400).json({
          success: false,
          message: "Aucun fichier spécifié.",
        });
      }

      const config = readMediaConfig();

      if (!config.homepage) {
        config.homepage = {};
      }

      if (!config.homepage.gallery) {
        config.homepage.gallery = {
          facades: [],
        };
      }

      let facades =
        config.homepage.gallery.facades || [];

      const existingIdx = facades.findIndex(
        (f) => Number(f.index) === targetIndex
      );

      if (existingIdx === -1) {
        return res.status(404).json({
          success: false,
          message:
            `Réalisation #${targetIndex} introuvable.`,
        });
      }

      let currentSubimages = (
        Array.isArray(
          facades[existingIdx].subimages
        )
          ? facades[existingIdx].subimages
          : []
      ).filter((file) =>
        checkFileExists(file)
      );

      incomingFiles.forEach((file) => {
        const existsOnDisk =
          checkFileExists(file);

        const foundIdx =
          currentSubimages.indexOf(file);

        if (foundIdx !== -1) {
          currentSubimages.splice(foundIdx, 1);
        } else if (existsOnDisk) {
          currentSubimages.push(file);
        }
      });

      facades[existingIdx].subimages =
        currentSubimages;

      config.homepage.gallery.facades =
        facades;

      if (!writeMediaConfig(config)) {
        return res.status(500).json({
          success: false,
          message:
            "Impossible d'enregistrer les sous-médias.",
        });
      }

      return res.json({
        success: true,
        message:
          `Sous-médias mis à jour pour la réalisation #${targetIndex} (${currentSubimages.length} valides).`,
        facade: facades[existingIdx],
        subimages: currentSubimages,
      });
    } catch (err) {
      console.error(
        "❌ PUT subimages error:",
        err
      );

      return res.status(500).json({
        success: false,
        message:
          "Erreur enregistrement sous-médias.",
      });
    }
  }
);

// BATCH DELETE FACADES (PROTECTED)
router.delete(
  "/gallery",
  requireAdminAuth,
  (req, res) => {
    try {
      const { indices } = req.body || {};

      if (
        !Array.isArray(indices) ||
        !indices.length
      ) {
        return res.status(400).json({
          success: false,
          message:
            "Indices invalides ou manquants.",
        });
      }

      const targetIndices =
        indices.map((i) => Number(i));

      const config = readMediaConfig();

      let facades = (
        config.homepage?.gallery?.facades || []
      )
        .filter(
          (f) =>
            !targetIndices.includes(
              Number(f.index)
            )
        )
        .map((item, idx) => ({
          ...item,
          index: idx + 1,
        }));

      if (!config.homepage) {
        config.homepage = {};
      }

      if (!config.homepage.gallery) {
        config.homepage.gallery = {};
      }

      config.homepage.gallery.facades =
        facades;

      if (!writeMediaConfig(config)) {
        return res.status(500).json({
          success: false,
          message:
            "Impossible de modifier la galerie.",
        });
      }

      return res.json({
        success: true,
        facades,
      });
    } catch (err) {
      console.error(
        "❌ DELETE batch gallery error:",
        err
      );

      return res.status(500).json({
        success: false,
        message:
          "Erreur suppression galerie.",
      });
    }
  }
);

